'use strict';

/**
 * Create Vapi Assistant
 *
 * Reads the generated assistant config (config/assistant.json) and creates
 * a Vapi assistant via the API. Saves the assistant ID to .env.
 *
 * Usage:
 *   node scripts/create-assistant.js
 *
 * Prerequisites:
 *   - Run `node scripts/generate-assistant-config.js` first
 *   - Set VAPI_PRIVATE_KEY in .env
 */

const fs = require('fs');
const path = require('path');
require('dotenv').config();

const vapiClient = require('./lib/vapi-client');

async function main() {
  // 1. Read the generated assistant config
  const configPath = path.join(__dirname, '..', 'config', 'assistant.json');

  if (!fs.existsSync(configPath)) {
    console.error('Error: config/assistant.json not found.');
    console.error('Run `node scripts/generate-assistant-config.js` first.');
    process.exit(1);
  }

  const assistantConfig = JSON.parse(fs.readFileSync(configPath, 'utf8'));

  console.log('Creating Vapi assistant...');
  console.log(`  Name: ${assistantConfig.name}`);
  console.log(`  Transcriber: ${assistantConfig.transcriber.provider}`);
  console.log(`  Model: ${assistantConfig.model.provider}`);
  console.log(`  Voice: ${assistantConfig.voice.provider}`);
  console.log(`  First message: ${assistantConfig.firstMessage.substring(0, 60)}...`);
  console.log('');

  // 2. Create the assistant via Vapi API
  const assistant = await vapiClient.createAssistant(assistantConfig);

  console.log('');
  console.log('Assistant created successfully!');
  console.log(`  ID: ${assistant.id}`);
  console.log(`  Name: ${assistant.name}`);
  console.log(`  Org ID: ${assistant.orgId}`);
  console.log('');

  // 3. Save assistant ID to .env
  const envPath = path.join(__dirname, '..', '.env');
  let envContent = '';

  if (fs.existsSync(envPath)) {
    envContent = fs.readFileSync(envPath, 'utf8');
  }

  // Update or add VAPI_ASSISTANT_ID
  if (envContent.includes('VAPI_ASSISTANT_ID=')) {
    envContent = envContent.replace(
      /VAPI_ASSISTANT_ID=.*/,
      `VAPI_ASSISTANT_ID=${assistant.id}`
    );
  } else {
    envContent += `\n# Vapi Assistant ID (auto-generated by create-assistant.js)\nVAPI_ASSISTANT_ID=${assistant.id}\n`;
  }

  fs.writeFileSync(envPath, envContent.trim() + '\n');

  console.log(`Saved VAPI_ASSISTANT_ID=${assistant.id} to .env`);
  console.log('');
  console.log('Next steps:');
  console.log('  - To make a call: node scripts/make-call.js --phone=+91XXXXXXXXXX --name=रोहन --drug=Crocin');
  console.log('  - To run a simulation: node scripts/run-simulation.js');
  console.log('  - To update the assistant: node scripts/update-assistant.js');
}

main().catch((err) => {
  console.error('Error:', err.message);
  process.exit(1);
});
